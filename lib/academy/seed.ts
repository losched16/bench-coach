// BenchCoach Academy — a parsed manuscript → one idempotent SQL script.
//
// Re-runnable and safe on a live course:
//   * never touches status, price or Stripe ids (those are the owner's);
//   * a lesson that disappeared from the manuscript becomes 'draft' instead
//     of being deleted, so nobody's reading progress is lost;
//   * unresolved editorial flags are replaced; resolved ones are kept.

import { createHash } from 'crypto'
import type { ParsedCourse } from './manuscript'
import type { CourseCopy } from './catalog'

const q = (v: string | null | undefined) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)
const n = (v: number | null | undefined) => (v == null ? 'NULL' : String(Math.trunc(v)))
const b = (v: boolean) => (v ? 'true' : 'false')

export function sha256(s: string): string {
  return createHash('sha256').update(s).digest('hex')
}

export function seedSql(course: ParsedCourse, copy: CourseCopy, opts: { bumpVersion?: boolean } = {}): string {
  const C = `(SELECT id FROM public.academy_courses WHERE slug = ${q(course.slug)})`
  const out: string[] = []
  out.push('-- Generated by scripts/academy/import-course.ts. PRIVATE: contains paid course text.')
  out.push('-- Do not commit. Paste into the Supabase SQL editor after migration 080.')
  out.push('BEGIN;')
  out.push(
    `INSERT INTO public.academy_courses (slug, title, subtitle, summary, preview_lesson_key, safety_note, related_pathway_slug)
VALUES (${q(course.slug)}, ${q(course.title)}, ${q(course.subtitle)}, ${q(copy.subheadline)}, ${q(copy.previewLessonKey)}, ${q(course.safetyText)}, ${q(copy.relatedPathwaySlug)})
ON CONFLICT (slug) DO UPDATE SET title = EXCLUDED.title, subtitle = EXCLUDED.subtitle, summary = EXCLUDED.summary,
  preview_lesson_key = EXCLUDED.preview_lesson_key, safety_note = EXCLUDED.safety_note,
  related_pathway_slug = EXCLUDED.related_pathway_slug${opts.bumpVersion ? ', content_version = public.academy_courses.content_version + 1' : ''};`,
  )
  // Free the unique positions before re-numbering.
  out.push(`UPDATE public.academy_lessons SET position = position + 10000 WHERE course_id = ${C};`)
  out.push(`UPDATE public.academy_modules SET position = position + 10000 WHERE course_id = ${C};`)
  for (const m of course.modules) {
    out.push(
      `INSERT INTO public.academy_modules (course_id, module_key, position, title, subtitle, outcome)
VALUES (${C}, ${q(m.key)}, ${n(m.position)}, ${q(m.title)}, ${q(m.subtitle)}, ${q(m.outcome)})
ON CONFLICT (course_id, module_key) DO UPDATE SET position = EXCLUDED.position, title = EXCLUDED.title, subtitle = EXCLUDED.subtitle, outcome = EXCLUDED.outcome;`,
    )
  }
  for (const l of course.lessons) {
    out.push(
      `INSERT INTO public.academy_lessons (course_id, lesson_key, module_key, kind, position, number_label, title, est_minutes, is_preview, status)
VALUES (${C}, ${q(l.key)}, ${q(l.moduleKey)}, ${q(l.kind)}, ${n(l.position)}, ${q(l.numberLabel)}, ${q(l.title)}, ${n(l.estMinutes)}, ${b(l.isPreview)}, 'published')
ON CONFLICT (course_id, lesson_key) DO UPDATE SET module_key = EXCLUDED.module_key, kind = EXCLUDED.kind, position = EXCLUDED.position,
  number_label = EXCLUDED.number_label, title = EXCLUDED.title, est_minutes = EXCLUDED.est_minutes, is_preview = EXCLUDED.is_preview, status = 'published';`,
    )
    const blocks = JSON.stringify(l.blocks)
    out.push(
      `INSERT INTO public.academy_lesson_bodies (course_id, lesson_key, blocks, field_test, source_hash)
VALUES (${C}, ${q(l.key)}, ${q(blocks)}::jsonb, ${q(l.fieldTest)}, ${q(sha256(blocks + (l.fieldTest || '')))})
ON CONFLICT (course_id, lesson_key) DO UPDATE SET blocks = EXCLUDED.blocks, field_test = EXCLUDED.field_test, source_hash = EXCLUDED.source_hash, updated_at = now();`,
    )
  }
  const keys = course.lessons.map(l => q(l.key)).join(', ')
  // Retired lessons: hidden, never deleted (progress rows reference them).
  const pos = course.lessons.length
  out.push(
    `UPDATE public.academy_lessons SET status = 'draft', position = ${pos + 1} + (position - 10000) WHERE course_id = ${C} AND lesson_key NOT IN (${keys}) AND position >= 10000;`,
  )
  out.push(`DELETE FROM public.academy_editorial_flags WHERE course_id = ${C} AND resolved_at IS NULL;`)
  for (const f of course.flags) {
    out.push(
      `INSERT INTO public.academy_editorial_flags (course_id, lesson_key, flag, detail)
SELECT ${C}, ${q(f.lessonKey)}, ${q(f.flag)}, ${q(f.detail)}
WHERE NOT EXISTS (SELECT 1 FROM public.academy_editorial_flags WHERE course_id = ${C} AND lesson_key IS NOT DISTINCT FROM ${q(f.lessonKey)} AND flag = ${q(f.flag)});`,
    )
  }
  out.push('COMMIT;')
  out.push(`-- Then, when you are ready to sell (your decision, see docs/academy/DECISIONS.md):
--   UPDATE public.academy_courses SET price_cents = <cents>, stripe_price_id = 'price_…', status = 'published'
--   WHERE slug = ${q(course.slug)};`)
  return out.join('\n\n') + '\n'
}
